const here = path.dirname(fileURLToPath(import.meta.url));
const URDU = fs.readFileSync(path.join(here, '..', '..', 'data', 'fixtures', 'SYNTHETIC_hearsay_urdu_lesson.md'), 'utf8');
const pad = (n) => String(n).padStart(2, '0');
const icsStamp = (d) => d.toISOString().replace(/[-:]/g, '').replace(/\.\d{3}/, '');
const hearsayName = (d) => `transcript_${d.getFullYear()}${pad(d.getMonth() + 1)}${pad(d.getDate())}_${pad(d.getHours())}${pad(d.getMinutes())}${pad(d.getSeconds())}.md`;
const tmpDir = (p) => fs.mkdtempSync(path.join(os.tmpdir(), `cc-${p}-`));

function ics(events) {
  const body = events
    .map(
      (e) =>
        `BEGIN:VEVENT\r\nUID:${e.uid}\r\nDTSTART${e.tzStart || `:${icsStamp(e.start)}`}\r\nDTEND${e.tzEnd || `:${icsStamp(e.end)}`}\r\n${e.rrule ? `RRULE:${e.rrule}\r\n` : ''}${e.exdate ? `EXDATE${e.exdate}\r\n` : ''}${e.status ? `STATUS:${e.status}\r\n` : ''}SUMMARY:${e.summary}\r\nEND:VEVENT\r\n`
    )
    .join('');
  return `BEGIN:VCALENDAR\r\nVERSION:2.0\r\nPRODID:-//test//EN\r\n${body}END:VCALENDAR\r\n`;
}

/** Hearsay-style file content recorded at `d`, from the synthetic Urdu fixture. */
function hearsayText(d, extra = '') {
  return URDU.replace(/^# Transcript - .*$/m, `# Transcript - ${d.toLocaleDateString('en-CA')} ${pad(d.getHours())}:${pad(d.getMinutes())}`) + extra;
}

function fakeTranslator() {
  const calls = { translate: 0, analyse: 0 };
  setAiClientForTests({
    beta: {
      messages: {
        parse: async (params) => {
          const user = params.messages[0].content;
          if (/translat/i.test(params.system)) {
            calls.translate++;
            const ns = [...user.matchAll(/\[#(\d+)\]/g)].map((m) => Number(m[1]));
            const english = {
              1: 'Hello. Today we will clone the repository from GitHub. I have opened the terminal.',
              2: 'Okay, now run git clone https://github.com/demo/repo.git and then cd into the folder. Did the clone work?',
              3: 'Yes, I ran git clone and it worked. But we did not run git fetch today.',
            };
            return { stop_reason: 'end_turn', model: params.model, usage: { input_tokens: 100, output_tokens: 50 }, parsed_output: { segments: ns.map((n) => ({ n, english: english[n] || `line ${n}` })) } };
          }
          calls.analyse++;
          return { stop_reason: 'end_turn', model: params.model, usage: {}, parsed_output: { findings: [], commands_executed: [], commands_mentioned_only: [], difficulties: [], decisions: [], tutor_feedback: [], homework: [], unresolved_questions: [], topics: [] } };
        },
        create: async () => ({ stop_reason: 'end_turn', content: [{ type: 'text', text: 'ok' }] }),
      },
    },
  });
  return calls;
}

