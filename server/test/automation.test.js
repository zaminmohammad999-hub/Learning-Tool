  assert.equal(byId.L03.planned_date, new Date(events[1].start).toLocaleDateString('en-CA'), 'L02 is manual, so the next slot goes to L03');

  // An occurrence removed from the feed is marked cancelled and its lesson date released.
  setCalendarSourceForTests(async () => ics(events.slice(0, 3)));
  await request(app).post('/api/automation/calendar/sync').send({}).expect(200);
