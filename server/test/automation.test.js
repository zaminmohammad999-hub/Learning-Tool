  const day = 86400000;
  const base = new Date(Date.now() + 2 * day);
  base.setUTCHours(18, 0, 0, 0);
  const events = [0, 3, 7, 10].map((k, i) => ({ uid: `vc${i}@x`, start: new Date(base.getTime() + k * day), end: new Date(base.getTime() + k * day + 3600000), summary: 'Vibe Coding' }));
